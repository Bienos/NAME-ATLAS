#!/usr/bin/env tsx
/**
 * Writes the given-name list-facts artefact,
 * `packages/truth/src/generated/given-name-list-facts.ts` (TASK-178, ADR-0051,
 * `docs/contracts/given-name-list-facts.md`).
 *
 *   pnpm truth:given-name-list-facts [--dir data]
 *
 * Reads every resource of `BIRTH_NAME_RESOURCES` from
 * `data/birth-names-{resource_id}.csv`, refuses any file whose size, SHA-256,
 * row count or people sum is not the registry's (`births-registry.ts`),
 * computes each list's facts on its own and the comparisons of the lists'
 * sets of names, validates the artefact against
 * `givenNameListFactsArtefactSchema` and writes it formatted with the
 * repository's Prettier configuration (the header records the version used).
 *
 * Deterministic: a second run over the same bytes, with the same Prettier,
 * writes a byte-identical file. `data/` is git-ignored and CI has no copy, so
 * CI never runs this; it checks the committed artefact instead
 * (`src/given-name-list-facts/artefact.test.ts`). Exits non-zero, writing
 * nothing, on any refusal.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig, version as prettierVersion } from "prettier";
import { BIRTH_NAME_RESOURCES } from "@name-atlas/sources";
import type { BirthNameResourceDescriptor } from "@name-atlas/sources";
import { GIVEN_NAME_LIST_FACTS_SCHEMA_VERSION } from "@name-atlas/contracts";
import {
  GivenNameListFactsRefusedError,
  buildGivenNameListFactsArtefact,
} from "../src/given-name-list-facts/build.js";
import { GIVEN_NAME_LIST_FACTS_METHOD_VERSION } from "../src/version.js";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const outFile = path.join(repoRoot, "packages/truth/src/generated/given-name-list-facts.ts");

function dirArg(argv: readonly string[]): string {
  const i = argv.indexOf("--dir");
  const dir = i >= 0 ? argv[i + 1] : undefined;
  return dir === undefined ? path.join(repoRoot, "data") : path.resolve(dir);
}

/** Where the generator expects a resource's bytes: `data/birth-names-{id}.csv`. */
export function localBirthFileName(descriptor: BirthNameResourceDescriptor): string {
  return `birth-names-${descriptor.resource_id}.csv`;
}

async function readResource(
  descriptor: BirthNameResourceDescriptor,
  dir: string,
): Promise<Uint8Array> {
  const file = path.join(dir, localBirthFileName(descriptor));
  try {
    return new Uint8Array(await readFile(file));
  } catch (cause: unknown) {
    if ((cause as NodeJS.ErrnoException).code === "ENOENT") {
      throw new Error(
        `${file} is missing: download resource ${descriptor.resource_id} from ` +
          `${descriptor.official_source_url} into ${dir}`,
      );
    }
    throw cause;
  }
}

async function main(): Promise<void> {
  const dir = dirArg(process.argv.slice(2));
  const inputs = await Promise.all(
    BIRTH_NAME_RESOURCES.map(async (descriptor) => ({
      descriptor,
      bytes: await readResource(descriptor, dir),
    })),
  );
  const artefact = buildGivenNameListFactsArtefact(inputs);
  const header =
    "/**\n" +
    " * GENERATED by packages/truth/bin/build-given-name-list-facts.ts — do not edit.\n" +
    " *\n" +
    ` * Given-name list facts, schema ${GIVEN_NAME_LIST_FACTS_SCHEMA_VERSION}, pipeline ` +
    `${GIVEN_NAME_LIST_FACTS_METHOD_VERSION}\n` +
    " * (TASK-178, ADR-0051, docs/contracts/given-name-list-facts.md): statistics about each\n" +
    " * whole published first-name list of dataset 219, one list per year of birth and sex,\n" +
    " * the boys' and the girls' lists and the lists of different years apart, never summed.\n" +
    " * A first name appears only as ADR-0051 §2.4's selections, each at 100 children or more\n" +
    " * on its list. Regenerate with `pnpm truth:given-name-list-facts`; the files are not\n" +
    ` * committed. Formatted with Prettier ${prettierVersion}.\n` +
    " */\n" +
    'import type { GivenNameListFactsArtefact } from "@name-atlas/contracts";\n\n' +
    "export const GIVEN_NAME_LIST_FACTS_DATA: GivenNameListFactsArtefact = ";
  const source = `${header}${JSON.stringify(artefact, null, 2)};\n`;
  const config = (await resolveConfig(outFile)) ?? {};
  const formatted = await format(source, { ...config, filepath: outFile });
  await writeFile(outFile, formatted, "utf8");
  const years = `${String(artefact.first_year)}–${String(artefact.last_year)}`;
  console.log(
    `wrote ${path.relative(repoRoot, outFile)}: ${String(artefact.resources.length)} resources, ` +
      `${years}, boys' and girls' lists apart`,
  );
}

main().catch((cause: unknown) => {
  if (cause instanceof GivenNameListFactsRefusedError) {
    console.error(`refused (${cause.reason}): ${cause.message}`);
  } else {
    console.error(cause);
  }
  process.exitCode = 1;
});
