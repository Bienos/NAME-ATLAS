#!/usr/bin/env tsx
/**
 * Writes the list-facts artefact, `packages/truth/src/generated/list-facts.ts`
 * (TASK-040, TASK-043, TASK-044, ADR-0015, ADR-0018, ADR-0019,
 * TASK-106, `docs/contracts/list-facts.md`).
 *
 *   pnpm fetch:pesel --series      # every edition a trend reads, 2019 included, byte-exact, into data/
 *   pnpm truth:list-facts [--dir data]
 *
 * Reads every edition of each national list that a trend reads
 * (`PESEL_TREND_EDITIONS`: `national-male-2019-06-30.csv`, then the series
 * `national-male-2020-01-22.csv` … `national-male-2026-01-20.csv`, and the
 * female list's; ADR-0019 §2.2 as amended by TASK-106), refuses any file that is not the registry's pinned bytes
 * (size, SHA-256 and row count, through the completeness gate), refuses a
 * publisher duplicate as an edition and records the registry's refused
 * resources as gaps (ADR-0019 §2.2), computes each list's facts on its own
 * (the 2026 edition's `list_facts@2` sections, and `editions` and `change`
 * over its series), validates the artefact against `listFactsArtefactSchema` and
 * writes it formatted with the repository's Prettier configuration, through
 * Prettier's API (`prettier`, pinned as this package's devDependency to the
 * root's exact version; the header records the version used).
 *
 * Deterministic: the seeded examples use fixed seeds, so a second run over
 * the same bytes, with the same Prettier, writes a byte-identical file.
 *
 * `data/` is git-ignored and CI has no copy, so CI never runs this; it checks
 * the committed artefact instead (`src/list-facts/artefact.test.ts`).
 * Exits non-zero, writing nothing, on any refusal.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig, version as prettierVersion } from "prettier";
import {
  PESEL_REFUSED_RESOURCES,
  PESEL_SERIES_KEYS,
  PESEL_TREND_EDITIONS,
  localFileName,
} from "@name-atlas/sources";
import type { PeselRefusedResource, PeselResourceDescriptor } from "@name-atlas/sources";
import { ListFactsRefusedError, buildListFactsArtefact } from "../src/list-facts/build.js";
import type { SeriesInput } from "../src/list-facts/build.js";
import { LIST_FACTS_SCHEMA_VERSION, NAMED_SURNAME_FLOOR } from "@name-atlas/contracts";
import { LIST_FACTS_METHOD_VERSION } from "../src/version.js";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const outFile = path.join(repoRoot, "packages/truth/src/generated/list-facts.ts");

function dirArg(argv: readonly string[]): string {
  const i = argv.indexOf("--dir");
  const dir = i >= 0 ? argv[i + 1] : undefined;
  return dir === undefined ? path.join(repoRoot, "data") : path.resolve(dir);
}

async function readList(descriptor: PeselResourceDescriptor, dir: string): Promise<Uint8Array> {
  const file = path.join(dir, localFileName(descriptor));
  try {
    return new Uint8Array(await readFile(file));
  } catch (cause: unknown) {
    if ((cause as NodeJS.ErrnoException).code === "ENOENT") {
      throw new Error(`${file} is missing; run \`pnpm fetch:pesel --series\` first`, { cause });
    }
    throw cause;
  }
}

/**
 * Every edition of one list a trend reads (its 2019 edition, then its series), read
 * from `dir`, and the resources refused from the series.
 */
async function readSeries(
  partition: keyof typeof PESEL_TREND_EDITIONS,
  dir: string,
): Promise<SeriesInput> {
  const editions = [];
  for (const descriptor of PESEL_TREND_EDITIONS[partition]) {
    editions.push({ descriptor, bytes: await readList(descriptor, dir) });
  }
  const series = PESEL_SERIES_KEYS[partition];
  return { editions, refused: PESEL_REFUSED_RESOURCES.filter((r) => r.series === series) };
}

function header(
  lists: readonly PeselResourceDescriptor[],
  editions: readonly PeselResourceDescriptor[],
  refused: readonly PeselRefusedResource[],
): string {
  const line = (d: { role: string; resource_id: string; data_date: string }, sha: string) =>
    ` *   ${d.role.padEnd(16)} ${d.data_date}  resource ${d.resource_id.padEnd(7)}  sha256 ${sha}`;
  return [
    "/**",
    " * GENERATED by packages/truth/bin/build-list-facts.ts — do not edit.",
    " *",
    ` * List facts, schema ${LIST_FACTS_SCHEMA_VERSION}, pipeline ${LIST_FACTS_METHOD_VERSION}`,
    " * (TASK-040, TASK-043, TASK-044, TASK-106, ADR-0015, ADR-0018, ADR-0019, docs/contracts/list-facts.md):",
    " * statistics about each whole published national PESEL list, the male list and the female",
    " * list apart, never summed or merged; `overlap` compares their sets of surnames, as counts",
    " * of surnames. The only surname strings are ADR-0018's named selections, each chosen",
    ` * by a fixed list-scope rule and each at ${NAMED_SURNAME_FLOOR} people or more on its list.`,
    " * `editions` and `change` compare each list with the earlier editions of its own series",
    " * (ADR-0019), preceded by its 2019-06-30 edition, in no series and described in fewer",
    " * words (TASK-106): list-scope figures only, never across the two lists, never a cause.",
    " *",
    ` * Computed from dane.gov.pl dataset 1681, reference date ${lists[0]?.data_date ?? ""}:`,
    ...lists.map((d) => line(d, d.official_sha256)),
    " * and from the earlier editions of each list (its 2019 edition, then its series):",
    ...editions.map((d) => line(d, d.official_sha256)),
    " * Refused as editions (recorded as gaps):",
    ...refused.map((r) => `${line(r, r.official_sha256)}  ${r.reason} of ${r.duplicate_of}`),
    " * It is valid only for these exact bytes.",
    " *",
    " * To regenerate: `pnpm fetch:pesel --series && pnpm truth:list-facts` (a second run over the",
    ` * same bytes writes a byte-identical file). Formatted with Prettier ${prettierVersion}.`,
    " * Read it through `listFacts()`.",
    " */",
  ].join("\n");
}

async function main(): Promise<void> {
  const dir = dirArg(process.argv.slice(2));
  const started = Date.now();
  const artefact = buildListFactsArtefact({
    male: await readSeries("national_male", dir),
    female: await readSeries("national_female", dir),
  });

  const male = PESEL_TREND_EDITIONS.national_male;
  const female = PESEL_TREND_EDITIONS.national_female;
  const source =
    `${header(
      [male[male.length - 1]!, female[female.length - 1]!],
      [...male.slice(0, -1), ...female.slice(0, -1)],
      PESEL_REFUSED_RESOURCES,
    )}\n` + `export const LIST_FACTS_DATA = ${JSON.stringify(artefact)};\n`;
  const options = (await resolveConfig(outFile)) ?? {};
  const formatted = await format(source, { ...options, filepath: outFile });
  await writeFile(outFile, formatted, "utf8");

  for (const key of ["male", "female"] as const) {
    const list = artefact.lists[key];
    console.log(
      `[list-facts] ${list.partition} (${list.source.external_record_id}): ` +
        `${list.summary.people} people, ${list.summary.surnames} surnames, ` +
        `collision n_half ${list.collision.n_half}, pair 1 in ${list.collision.pair_one_in}, ` +
        `${list.dots.histogram.length} distinct counts, top letter ${list.initials.top}, ` +
        `named ${list.named_top.items.map((item) => item.published).join(" ")}`,
    );
    const { editions, change } = list;
    console.log(
      `[list-facts] ${list.partition} series ${editions.series}: ` +
        editions.items
          .map((e) => `${e.data_date} ${e.resource_id} ${e.surnames}/${e.people}`)
          .join(", ") +
        editions.gaps
          .map((g) => `; gap ${g.data_date} ${g.resource_id} ${g.reason} of ${g.duplicate_of}`)
          .join(""),
    );
    console.log(
      `[list-facts] ${list.partition} change ${change.first_data_date} → ${change.last_data_date}: ` +
        `surnames ${change.surnames_delta}, people ${change.people_delta}, ` +
        `on last not first ${change.on_last_not_first.surnames} ` +
        `(${change.on_last_not_first.people} people), on first not last ` +
        `${change.on_first_not_last.surnames}, top 3 first ` +
        `${change.top3_first_counts.map((t) => `${t.key} ${t.count_first ?? "not on the list"}`).join(", ")}, ` +
        `top 10 unchanged ${change.top10_unchanged}`,
    );
  }
  const { overlap } = artefact;
  console.log(
    `[list-facts] overlap (surnames): male only ${overlap.male_only}, both ${overlap.both}, ` +
      `female only ${overlap.female_only}`,
  );
  console.log(`[list-facts] wrote ${path.relative(repoRoot, outFile)}`);
  console.error(`[list-facts] done in ${((Date.now() - started) / 1000).toFixed(1)}s`);
}

main().catch((cause: unknown) => {
  if (cause instanceof ListFactsRefusedError) {
    console.error(`[list-facts] refused (${cause.reason}): ${cause.message}`);
  } else {
    console.error(`[list-facts] failed: ${cause instanceof Error ? cause.message : String(cause)}`);
  }
  process.exitCode = 1;
});
