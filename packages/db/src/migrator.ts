import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { FileMigrationProvider, Migrator } from "kysely/migration";
import type { Kysely } from "kysely";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/** Absolute path to the hand-written SQL migration files (ADR-0002). */
export const MIGRATIONS_DIR = path.resolve(__dirname, "../migrations");

/**
 * Creates a Kysely Migrator reading ordered, hand-written migration files
 * from {@link MIGRATIONS_DIR} via Kysely's `FileMigrationProvider`
 * (ADR-0002). Each migration is TypeScript authoring explicit SQL through
 * the `sql` tag — never generated by diffing a model.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any -- matches Kysely's own Migration/Migrator signature (Kysely<any>).
export function createMigrator(db: Kysely<any>): Migrator {
  return new Migrator({
    db,
    provider: new FileMigrationProvider({
      fs,
      path,
      migrationFolder: MIGRATIONS_DIR,
    }),
  });
}
